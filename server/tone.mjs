// 「AI 味」套话清单：网页文案（tests/plain.test.ts）和 AI 回答（server/ask.mjs）共用这一份。
// 来由：2026-11-11 有用户说解读「AI 味儿重，尤其是那个『别慌』，太多 AI 跟我说过别慌了」。
// 这些话单看不算错，但几乎每个 AI 都在用，读的人一眼就认出来，也就不再相信后面的内容。
export const CLICHES=[
 '别慌','别担心','不用担心','别害怕','别着急','不用着急','不要着急','慢慢来','一步一步来',
 '深呼吸','抱抱','拥抱自己','温柔地对待','温柔对待','善待自己','接纳自己','允许自己',
 '给自己一点时间','给自己一点耐心','给自己一点肯定','给自己一些时间',
 '你值得','值得被','比想象中更','比你想象的更','你会发现','这也是一种成长','这本身就是一种',
 '你并不孤单','你已经做得很好','你辛苦了','一切都会好起来','都会过去的','要相信自己','请相信自己',
 '每一步都算数','都是在为','没有对错','听从内心','内心的声音','跟随你的心',
];
/** 「不是……而是……」的翻转句：一段话里用一次可以，用两次以上就是套路 */
const FLIP=/不是[^。！？\n]{1,24}?而是/g;
/** 返回命中的套话（去重），没有就是空数组。dash：破折号也算（AI 回答里算；网页牌面描述里少量保留） */
export function cliches(text,{dash=true}={}){
 if(typeof text!=='string')return [];
 const hit=CLICHES.filter(w=>text.includes(w));
 if((text.match(FLIP)||[]).length>=2)hit.push('不是……而是……（用了两次以上）');
 if(dash&&/——/.test(text))hit.push('破折号（——）');
 return [...new Set(hit)];
}
